#!/usr/bin/env python3
"""Enforces the plugin policy from docs/17-tech-stack.md.

    python tools/check_plugins.py            # report, exit 1 on a violation
    python tools/check_plugins.py --list     # just show what is enabled

Doc 17: "Every third-party plugin is something that can block a 5.8 to 5.9 migration.
Take them deliberately and sparingly."

The policy is not "no plugins" - it is that every one is a decision somebody made on
purpose and wrote down. This file is that written-down list. A plugin appearing in the
uproject without an entry here is the thing being caught: not because it is necessarily
wrong, but because it arrived without anyone recording why.

Deliberately plain Python with no UE dependency, so it runs in CI in under a second
without an engine install.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
UPROJECT = os.path.join(HERE, "..", "game", "Ichor.uproject")

# name -> (allowed target scope, why it is here)
#
# "Editor" means it must carry a TargetAllowList of exactly ["Editor"] - it may not ship
# in the packaged game. Anything a player never runs should not be in the binary they get,
# and a plugin that only exists at edit time cannot block a runtime engine upgrade.
POLICY = {
    "PythonScriptPlugin": (
        "Editor",
        "Every asset in this project is generated by a script rather than authored by "
        "hand. First-party Epic; edit time only.",
    ),
    "ModelingToolsEditorMode": (
        "Editor",
        "Ships with the engine and is the editor half of Geometry Script. First-party "
        "Epic; edit time only.",
    ),
    "GeometryScripting": (
        "Editor",
        "Generates the arena props and the earlier weapon pass. Its output is baked "
        "StaticMesh assets, so nothing at runtime needs it. First-party Epic.",
    ),
}


def load_plugins():
    with open(UPROJECT, encoding="utf-8") as f:
        return json.load(f).get("Plugins", [])


def scope_of(entry):
    allow = entry.get("TargetAllowList")
    if not allow:
        return "All"
    return "Editor" if list(allow) == ["Editor"] else "+".join(allow)


def main():
    plugins = load_plugins()

    if "--list" in sys.argv:
        for p in plugins:
            print("{:<28} enabled={:<6} scope={}".format(
                p.get("Name", "?"), str(p.get("Enabled")), scope_of(p)))
        return 0

    problems = []
    for entry in plugins:
        name = entry.get("Name", "?")
        if not entry.get("Enabled", False):
            continue

        if name not in POLICY:
            problems.append(
                "{} is enabled but has no policy entry. Add one in tools/check_plugins.py "
                "saying why it is worth the upgrade risk, or remove it.".format(name))
            continue

        wanted, _ = POLICY[name]
        actual = scope_of(entry)
        if actual != wanted:
            problems.append(
                "{} is scoped {} but policy says {}. An editor-only plugin shipping in the "
                "game is a runtime dependency nobody chose.".format(name, actual, wanted))

    enabled = {p.get("Name") for p in plugins if p.get("Enabled")}
    for name in POLICY:
        if name not in enabled:
            print("note: {} is in the policy but not enabled - stale entry?".format(name))

    if problems:
        print("PLUGIN POLICY VIOLATIONS ({}):".format(len(problems)))
        for p in problems:
            print("  - " + p)
        return 1

    print("plugin policy OK - {} enabled, all accounted for:".format(len(enabled)))
    for entry in plugins:
        if entry.get("Enabled"):
            name = entry.get("Name")
            print("  {:<26} {:<7} {}".format(name, scope_of(entry), POLICY[name][1].split(".")[0]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
